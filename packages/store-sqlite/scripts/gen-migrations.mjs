// Embeds `src/migrations/*.sql` into `src/migrations/sql.generated.ts` as string constants.
//
// Why: the .sql files are the reviewable source of truth, but the service is later bundled into
// a single file (P0-15), where runtime `readFileSync(new URL(..., import.meta.url))` would point
// at the wrong place. Embedding works the same under tsc, Vitest, esbuild and any later bundle.
// `migrate.test.ts` fails if the generated module is out of date.
//
// Usage: `npm run gen:migrations -w @emos/store-sqlite`
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../src/migrations/", import.meta.url));

function templateLiteral(text) {
  return `\`${text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${")}\``;
}

const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const entries = files.map((f) => {
  const sql = readFileSync(join(dir, f), "utf8").replaceAll("\r\n", "\n");
  return `  "${f.slice(0, -4)}": ${templateLiteral(sql)},`;
});

const out = `// GENERATED by scripts/gen-migrations.mjs from ./*.sql. Do not edit by hand.
// Regenerate: npm run gen:migrations -w @emos/store-sqlite
export const SQL = {
${entries.join("\n")}
} as const;
`;

writeFileSync(join(dir, "sql.generated.ts"), out);
console.log(`sql.generated.ts: ${files.length} migration(s)`);
